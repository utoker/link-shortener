// Slugs that can't be claimed as custom links: reqq.cc/<slug> would clash with
// an app route, a Next.js or static file, or a page we may add later.
// Matched case-insensitively, so "Admin" is reserved too.
const RESERVED_SLUGS = new Set([
  // app routes and files
  '404',
  '500',
  '_next',
  '_vercel',
  'api',
  'auth',
  'callback',
  'protected',
  'reset-password',
  'favicon',
  'icon',
  'apple-icon',
  'manifest',
  'robots',
  'sitemap',
  'opengraph-image',
  'twitter-image',
  'images',
  'fonts',
  'static',
  'public',
  'assets',
  'error',
  'not-found',
  // pages and paths a site like this commonly has
  'about',
  'terms',
  'tos',
  'privacy',
  'cookies',
  'legal',
  'contact',
  'help',
  'support',
  'faq',
  'docs',
  'blog',
  'pricing',
  'donate',
  'security',
  'abuse',
  'report',
  'status',
  'health',
  'home',
  'index',
  'app',
  'www',
  'mail',
  'admin',
  'dashboard',
  'account',
  'settings',
  'profile',
  'login',
  'logout',
  'signin',
  'signup',
  'sign-in',
  'sign-up',
  'register',
  'password',
  'forgot-password',
  'link',
  'links',
  'new',
  'create',
  'edit',
  'delete',
  'stats',
  'qr',
  'preview',
]);

export function isReservedSlug(slug: string): boolean {
  return RESERVED_SLUGS.has(slug.toLowerCase());
}
